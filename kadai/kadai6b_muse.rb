#上の2つの配列は変換ツールで作った名画4枚のデータである（1枚目は北斎、2枚目はゴッホ、3枚目はモネ、4枚目はクリムト）

Pixel = Struct.new(:r, :g, :b)
$img = Array.new(200) do
  Array.new(300) do Pixel.new(255,255,255) end
end

def pset(x, y, r=0, g=0, b=0, a=0.0)
  if x < 0 || x >= 300 || y < 0 || y >= 200 then return end
  $img[y][x].r = ($img[y][x].r * a + r * (1.0 - a)).to_i
  $img[y][x].g = ($img[y][x].g * a + g * (1.0 - a)).to_i
  $img[y][x].b = ($img[y][x].b * a + b * (1.0 - a)).to_i
end

def writeimage(name)
  open(name, "wb") do |f|
    f.puts("P6\n300 200\n255")
    $img.each do |a|
      a.each do |p| f.write(p.to_a.pack("ccc")) end
    end
  end
end

def fillrect(x, y, w, h, r=0, g=0, b=0, a=0.0)
  j0 = (y-0.5*h).to_i; j1 = (y+0.5*h).to_i
  i0 = (x-0.5*w).to_i; i1 = (x+0.5*w).to_i
  j0.step(j1) do |j|
    i0.step(i1) do |i|
      if block_given? then yield(i,j) else pset(i,j,r,g,b,a) end
    end
  end
end

#波の中心と半径（中心は画面の左辺の中央の点（0，100）で3つの波に共通であり半径は外側から233と160と97である）
#半径の決め方はメソッド説明の後ろにある選定理由に書いた通りドットの数を数えて決めた
$center_x = 0
$center_y = 100
$r1 = 233
$r2 = 160
$r3 = 97

#波の中心から点までの距離を返す（引数xとyは調べる点の座標）
def distance_from_center(x, y)
  dx = x - $center_x
  dy = y - $center_y
  return Math.sqrt(dx * dx + dy * dy)
end

#点が波の内側にあるか調べる（引数xとyは調べる点の座標、引数radiusは波の半径、内側なら真を返し外側なら偽を返す）
def inside_wave(x, y, radius)
  if distance_from_center(x, y) < radius
    return true
  else
    return false
  end
end

#点の場所に何枚目の絵を表示するか決める（引数xとyはドットの中心の座標、戻り値は絵の番号で1枚目が0である、新しい波から順に調べる）
def choose_painting(x, y)
  if inside_wave(x, y, $r3)
    return 3
  elsif inside_wave(x, y, $r2)
    return 2
  elsif inside_wave(x, y, $r1)
    return 1
  else
    return 0
  end
end

#点が波の先頭の帯にあるか調べる（引数xとyはドットの中心の座標、帯は半径より12小さい円から半径の円までの間である）
def is_wave_front(x, y)
  d = distance_from_center(x, y)
  if d >= $r3 - 12 && d < $r3
    return true
  elsif d >= $r2 - 12 && d < $r2
    return true
  elsif d >= $r1 - 12 && d < $r1
    return true
  else
    return false
  end
end

#波の先頭にあるドットに白を重ねて光る輪にする（引数xとyはドットの中心の座標、白の透明度は0.6である）
def add_glow(x, y)
  if is_wave_front(x, y)
    fillrect(x, y, 8, 8, 255, 255, 255, 0.6)
  end
end

#ドットを1個塗る（引数colは列の番号、引数rowは行の番号、ドットは1辺が10の正方形のうち1辺が9の正方形だけを塗り残りが背景の隙間になる、fillrectは両端を含む範囲を塗るので幅と高さに8を指定すると9ピクセル分になる）
def paint_dot(col, row)
  x = col * 10 + 5
  y = row * 10 + 5
  painting = choose_painting(x, y)
  number = $paintings[painting][row][col]
  color = $palettes[painting][number]
  fillrect(x, y, 8, 8, color[0], color[1], color[2], 0.0)
  add_glow(x, y)
end

#画面全体を描いてファイルに書き出す（引数は無く背景を暗い色で塗ってから全てのドットを塗る）
def draw_picture
  fillrect(150, 100, 300, 200, 20, 20, 30, 0.0)
  20.times do |row|
    30.times do |col|
      paint_dot(col, row)
    end
  end
  writeimage("t.ppm")
end

