Pixel = Struct.new(:r, :g, :b)
$img = Array.new(200) do
  Array.new(300) do Pixel.new(255,255,255) end
end

def pset(x, y, r=0, g=0, b=0, a=0.0)
  if x < 0 || x >= 300 || y < 0 || y >= 200 then return end
  $img[y][x].r = ($img[y][x].r * a + r * (1.0 - a)).to_i
  $img[y][x].g = ($img[y][x].g * a + g * (1.0 - a)).to_i
  $img[y][x].b = ($img[y][x].b * a + b * (1.0 - a)).to_i
end

def writeimage(name)
  open(name, "wb") do |f|
    f.puts("P6\n300 200\n255")
    $img.each do |a|
      a.each do |p| f.write(p.to_a.pack("ccc")) end
    end
  end
end

def fillrect(x, y, w, h, r=0, g=0, b=0, a=0.0)
  j0 = (y-0.5*h).to_i; j1 = (y+0.5*h).to_i
  i0 = (x-0.5*w).to_i; i1 = (x+0.5*w).to_i
  j0.step(j1) do |j|
    i0.step(i1) do |i|
      if block_given? then yield(i,j) else pset(i,j,r,g,b,a) end
    end
  end
end

$cx = 300
$cy = 0
$cr = 175

def dist(x, y)
  return Math.sqrt((x-$cx)**2 + (y-$cy)**2)
end

def paintdot(col, row)
  x = col * 10 + 5; y = row * 10 + 5
  d = dist(x, y)
  k = 0
  if d < $cr then k = 1 end
  c = $palettes[k][$paintings[k][row][col]]
  fillrect(x, y, 8, 8, c[0], c[1], c[2])
  if d < $cr && d >= $cr - 10 then
    fillrect(x, y, 8, 8, 255, 255, 255, 0.3)
  end
  if d < $cr - 10 && d >= $cr - 20 then
    fillrect(x, y, 8, 8, 255, 255, 255, 0.65)
  end
end

def mypicture
  fillrect(150, 100, 300, 200, 20, 20, 30)
  20.times do |row|
    30.times do |col|
      paintdot(col, row)
    end
  end
  writeimage("t.ppm")
end

